"""What this board would actually grant, run and refuse — asked without
paying for a model.

`plans` answers which checkout a run works in. `profiles` answers what it
may do there and which files it is guaranteed. `verify` answers whether
the project's own checks passed and against what. `reviews` answers which
revision a reviewer judged. Every one of those is resolved before a
billable model is invoked — and until this module there was no way to
*ask* any of them without launching one.

So an operator discovered a mistyped policy the expensive way: move a
card, click **▸ start work**, watch the run refuse, read the ticker. A
required input that was not there, a check `review` could not ask for, a
`requires` naming a guarantee nothing enforces — each of them is a
sentence bench can produce in milliseconds, and each of them was only
ever produced by a launch.

## One evaluator, read from four distances

The thing this module must not be is a second opinion. It owns no policy
logic at all: it calls `profiles.resolve()` for each intent and reads the
`diagnostics` that came back, it calls `verify.request()` to run a check,
and it asks each adapter what *it* would generate. Every code it reports
is one `profiles.DIAGNOSTICS` names. If a doctor and a launch could ever
disagree, the doctor would be worse than nothing.

What it adds is *distance*, and saying honestly how far away each answer
is from the thing a person actually cares about:

    static       bench's own resolution. No process ran at all.
    generated    the installed adapter generated its vendor document,
                 through the `describe` interface it declares. Still no
                 vendor binary.
    stub         the adapter's own `run` executed, with a stub standing
                 in for the vendor CLI. Proves what bench and the adapter
                 *pass*; proves nothing about what the vendor enforces.
    runtime      bench's own check runner started a real process at a
                 fixture and waited on its exit status.
    real-agent   the installed vendor CLI ran a model.

The four cheap levels cannot be read as the expensive one, and that is
enforced here rather than left to a reader: `EVIDENCE` says what each
level proves and what it does not, `MODE_EVIDENCE` pins each mode to
exactly one level, and `report()` refuses to emit a finding whose level
does not match its mode. A `real-agent` finding nobody authorised is
`deferred`, in that word — never `passed`, and never absent.

## What it does, and what it only does when asked

`inspect()` reads. It resolves, it hashes, it reads files the policy
already approved, and it starts no process: a GET of it is free and
safe, which is why the page's inspector opens without a confirmation.

Everything else is opt-in by name, because each one does something:
`conformance` runs the adapter's own executables, `runtime` runs real
processes at a fixture it makes, `real-agent` spends money. Nothing here
touches the application, a card, a branch, a worktree, the live
services, or an operator's configuration — and nothing it makes outlives
it: a fixture is created under `local/state/doctor/` and removed, and
only ever one the doctor itself made.
"""

