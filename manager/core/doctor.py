# One level per mode, so a finding cannot be filed under a mode and claim
# the standing of another. `report()` enforces it.
MODE_EVIDENCE = {
    "inspect": "static",
    "conformance": "generated",
    "runtime": "runtime",
    "real-agent": "real-agent",
}

# A conformance finding that came out of the adapter's own `run` rather
# than its `describe` is a level stronger than the rest of its mode, and
# says so by name. The only exception, and it is listed rather than
# inferred.
STUB_FINDINGS = ("invocation", "exit-status")

OUTCOMES = {
    "passed": "bench asked, and the answer was the one it should be",
    "failed": "bench asked, and something is wrong — the cause and the "
              "remedy are on the row",
    "skipped": "there was nothing to ask: this board has not configured the "
               "thing the check is about, which is not a fault",
    "deferred": "this needs something the diagnosis was not given — an "
                "authorisation, or a guarantee nothing installed here "
                "enforces. Deliberately not 'passed'",
}

# Where the whole report lives and what that means for who can read it.
LOCATION = ("local to this board — it names this disk's paths, and nothing "
            "in it is committed, pushed or carried into a pull request")


def _finding(mode: str, name: str, outcome: str, about: str, detail: str, *,
             code: str | None = None, remedy: str | None = None,
             intent: str | None = None, evidence: str | None = None,
             extra: dict | None = None) -> dict:
    if outcome not in OUTCOMES:
        raise ValueError(f"unknown doctor outcome '{outcome}'")
    level = evidence or MODE_EVIDENCE[mode]
    if level not in EVIDENCE:
        raise ValueError(f"unknown evidence level '{level}'")
    found = {
        "id": f"{mode}:{name}" + (f":{intent}" if intent else ""),
        "mode": mode, "name": name, "intent": intent,
        "evidence": level, "outcome": outcome,
        "about": about, "detail": _redact(detail),
        "code": code, "remedy": remedy,
    }
    if extra:
        found.update(extra)
    return found


# ── redaction ──────────────────────────────────────────────────────────
#
# A diagnosis names exact operator-local paths on purpose: "the input is
# not there" is useless without saying where bench looked, and the report
# never leaves this machine. What it must never carry is a *value* — a
# token, a password, an environment variable's content — and the one place
# bytes bench did not write get in is a log or a subprocess's output. So
# everything that reaches a finding goes through `verify.scrub`, which is
# the same scrubber the evidence log uses, and nothing here ever reads an
# environment value in the first place.

def _redact(text: str) -> str:
    return verify.scrub(str(text or ""))


def redaction() -> dict:
    """What this report withholds, said out loud so a reader does not have
    to guess whether it is complete."""
    return {
        "paths": ("exact, because this report is local to the machine that "
                  "made it and a path is what an operator has to go and fix"),
        "values": ("no environment value, no credential and no approved "
                   "file's contents are read into this report at all — the "
                   "profile layer's allowlist has none to send"),
        "logs": ("a check's own output is scrubbed of anything "
                 "credential-shaped on the way out, by the same scrubber the "
                 "evidence sheet uses"),
        "location": LOCATION,
    }


# ── mode: inspect ──────────────────────────────────────────────────────


def example_worktree() -> Path:
    """The worktree root a reading resolves against when no card is named.

    A diagnosis is about the board rather than about one card, so there is
    no checkout to point at — and leaving the word out would make every
    grant that runs in a worktree read as *refused for want of a
    worktree*, which is a diagnostic about nothing. So the reading uses
    the path a card's worktree would be at, under the worktrees root this
    board actually resolves, and nothing is created there: `resolve` reads
    roots as words and only ever touches disk for the inputs inside one.
    """
    return config.WORKTREES / "a-card"


def _intent_reading(intent: str, worktree: Path | str | None,
                    policy: dict | None = None) -> dict:
    """One intent's resolved profile, through the resolver a launch rides.

    `review` is asked with no pinned checkout, because resolving one is
    not a reading: a PR review's checkout is provisioned by the launch,
    and the inspector must not create one to look at it. The reading says
    so rather than inventing a path.

    `policy` is passed straight through, for the two callers that read a
    document other than this board's: the fixture readings below, and the
    Settings editor validating a draft.
    """
    return profiles.resolve(intent, worktree=None if intent == "review"
                            else (worktree or example_worktree()),
                            policy=policy)


# The same reading, named for callers outside this module. `settings.py`
# shows the operator what each intent resolves to and validates drafts
# against it, and both have to be the reading the inspector takes — a
# Settings page that resolved with its own worktree convention would show
# a `grant-root-unavailable` the readiness inspector does not, about
# nothing. One function, one convention.
intent_reading = _intent_reading


def _public_intent(found: dict) -> dict:
    """The reading as the API and the page may see it: the profile layer's
    own allowlist, which has never carried a file's content."""
    out = profiles.public(found) or {}
    out["summary"] = profiles.summary(found)
    return out


def inspect(worktree: Path | str | None = None) -> dict:
    """Everything a reading can answer, and nothing a process can.

    Free and side-effect free in both halves of the word: it resolves,
    hashes and reads files the policy already approved, and it creates no
    branch, no worktree, no checkout, no evidence and no bundle. Opening
    the inspector runs this; that is why opening it is not an action.
    """
    doc = profiles.document()
    adapter = profiles.adapter_identity()
    table = profiles.capability_table(adapter)
    layout = config.layout()
    troubles = config.problems()

    findings: list[dict] = []

    # — the layout, which everything else is relative to —
    findings.append(_finding(
        "inspect", "roots", "failed" if troubles else "passed",
        "which application this board manages, where its tickets live, and "
        "where task branches are checked out",
        "; ".join(troubles) if troubles else
        (f"application {layout['app']} · work state {layout['work']} · "
         f"worktrees {layout['worktrees']} · tool {layout['tool']}"
         + (" · external layout" if layout["external"] else " · vendored")),
        remedy=("config.problems() is the single authority for this, and it "
                "fails closed: fix the roots named in manager/local/.env and "
                "re-run install.py. Bench will not fall back to a different "
                "repository.") if troubles else None))

    # — where the policy comes from —
    findings.append(_finding(
        "inspect", "policy", "failed" if doc["problem"] else
        ("skipped" if doc["kind"] == "legacy" else "passed"),
        "which document this board's execution policy comes from, and at "
        "which revision",
        doc["problem"] or
        (f"no profile document — this board resolves on BOARD_AGENT_COMMANDS "
         f"and each adapter's built-in grants, exactly as it did before "
         f"profiles existed"
         if doc["kind"] == "legacy" else
         f"{doc['identity']} at {(doc['revision'] or '')[:12]}"),
        code=("policy-unreadable" if doc["problem"] else None),
        remedy=(profiles.DIAGNOSTICS["policy-unreadable"][1]
                if doc["problem"] else None)))

    # — the adapter, and what it will answer for —
    declared = sorted(adapter["capabilities"])
    findings.append(_finding(
        "inspect", "adapter", "passed" if adapter["declared"] else "skipped",
        "which agent adapter this board launches through, and what it says it "
        "can genuinely enforce",
        f"{adapter['name']}"
        + (f" v{adapter['version']}" if adapter.get("version") else "")
        + (f" · enforces {', '.join(declared)}" if declared else "")
        + (f" · {adapter['note']}" if adapter.get("note") else ""),
        remedy=("An adapter without a capabilities.json promises nothing, "
                "which is honest and not an error — but a profile may then "
                "not require any guarantee of it.")
        if not adapter["declared"] else None))

    # — one reading per launch intent, and the diagnostics off each —
    #
    # And a row saying what these rows are *about*, because the honest
    # answer is "the shape of the policy" rather than "card 70": there is
    # no card here, so the worktree root is the path a card's would be at
    # and a selection inside a particular checkout is not what was read.
    findings.append(_finding(
        "inspect", "scope", "skipped",
        "which card these readings are about",
        f"none. A diagnosis resolves the policy for the board, so the "
        f"worktree root is the path a card's checkout would be at "
        f"({worktree or example_worktree()}) and nothing was created there. "
        f"A particular card's reading is the ⚿ chip on that card.",
        remedy=None))
    readings: list[dict] = []
    for intent in profiles.INTENTS:
        found = _intent_reading(intent, worktree)
        readings.append(_public_intent(found))
        findings += _intent_findings(intent, found)

    # — what a merge refuses without, which is not what a launch grants —
    gate_policy = profiles.gate_policy(doc)
    findings += _gate_findings(gate_policy)

    # — what nothing here enforces, named rather than omitted —
    findings += _pending_findings(table, readings)

    # — bench's own broken documents, through bench's own resolver —
    findings += fixture_findings()

    return {
        "layout": layout,
        "problems": troubles,
        # what this board refuses a merge without, per guarded scope. The
        # same resolution the merge path reads, reported and never
        # re-derived — this module owns no policy logic here either.
        "gates": profiles.gate_policy_public(gate_policy),
        "policy": {"kind": doc["kind"], "identity": doc["identity"],
                   "path": doc["path"], "revision": doc["revision"],
                   "describes": doc["describes"], "problem": doc["problem"],
                   "precedence": ["BOARD_AGENT_PROFILES",
                                  "manager/local/profiles.json",
                                  "BOARD_AGENT_COMMANDS and the adapter's "
                                  "built-in grants"]},
        "adapter": adapter,
        "capabilities": table,
        "intents": readings,
        "findings": findings,
    }


def _gate_findings(policy: dict) -> list[dict]:
    """What a merge on this board refuses without, per guarded scope.

    A reading at the `static` distance and nothing more: it resolves the
    operator's gate block and reports it. It reads no evidence, asks git
    nothing and decides no card's case — a particular card's gate is the
    ⚖ chip on that card, for the reason the `scope` row above gives.

    A board that declares no gate gets `skipped` rather than `passed`,
    which is the distinction this whole report is built on: nothing is
    required here, and nothing is proved.
    """
    out: list[dict] = []
    for scope, entry in sorted(policy["scopes"].items()):
        checks = ", ".join(c["name"] for c in entry["checks"])
        out.append(_finding(
            "inspect", f"gate:{scope}",
            "failed" if policy["blockers"] else
            ("passed" if entry["gated"] else "skipped"),
            entry["why"],
            (f"this board's gate policy does not resolve, so no gate can be "
             f"evaluated and none is assumed met: {policy['blockers'][0]}"
             if policy["blockers"] else
             f"requires {checks or 'no check'}"
             f" · review: {entry['review']} — {entry['reviewWhy']}"
             if entry["gated"] else
             "nothing is required here, so nothing is proved — a merge runs "
             "as it did before gates existed"),
            remedy=(profiles.DIAGNOSTICS["gate-check-undeclared"][1]
                    if policy["blockers"] else
                    ("Declare it in the document's \"gates\" block if this "
                     "board should refuse a merge without evidence. An "
                     "unconfigured gate is honest, not safe."
                     if not entry["gated"] else None))))
    for diagnostic in policy["diagnostics"]:
        out.append(_finding(
            "inspect", f"gate:{diagnostic['code']}", "failed",
            diagnostic["title"], diagnostic["why"],
            code=diagnostic["code"], remedy=diagnostic["remedy"]))
    out.append(_finding(
        "inspect", "gate:override", "skipped" if not
        policy["overrides"]["allowed"] else "passed",
        "whether a person may proceed over an unmet gate on this board, and "
        "what is recorded when they do",
        policy["overrides"]["why"]
        + (f" · allowed to: {', '.join(policy['overrides']['actors'])}"
           if policy["overrides"]["actors"] else "")
        + ". An override records the actor, the reason, the exact head and "
          "the exact gates that were unmet; it forges no evidence and "
          "authorises one commit",
        remedy=None))
    return out


def _intent_findings(intent: str, found: dict) -> list[dict]:
    """What one intent's resolution says, as rows a person acts on.

    The intent's own row leads with whether a launch would start, and then
    every refusal gets a row of its own carrying the code it came from and
    the remedy for the class of it. Nothing is re-derived here: `code`,
    `why` and `remedy` are all read off what `profiles.resolve()` already
    decided.
    """
    out = [_finding(
        "inspect", "launch", "failed" if found["blockers"] else "passed",
        f"whether a launch of '{intent}' would start on this board",
        found["blockers"][0] if found["blockers"] else
        (f"would run in {found['cwd']['path'] or found['cwd']['policy']} "
         f"({found['cwd']['policy']} root) · "
         f"{len(found['commands'])} command grant"
         f"{'' if len(found['commands']) == 1 else 's'} · "
         f"{len([i for i in found['context'] if i['readable']])} of "
         f"{len(found['context'])} approved input"
         f"{'' if len(found['context']) == 1 else 's'} readable · "
         f"{len(found['verify'])} named check"
         f"{'' if len(found['verify']) == 1 else 's'} it may ask bench for"),
        intent=intent,
        code=(found["diagnostics"][0]["code"] if found["diagnostics"] else None),
        remedy=(found["diagnostics"][0]["remedy"] if found["diagnostics"]
                else None))]

    for diagnostic in found["diagnostics"]:
        out.append(_finding(
            "inspect", diagnostic["code"], "failed",
            diagnostic["title"], diagnostic["why"],
            intent=intent, code=diagnostic["code"],
            remedy=diagnostic["remedy"]))

    # Can this intent get a check run at all? Three different answers, and
    # the middle one is the whole reason this row exists: a board that
    # declares checks for `work` and forgets `review` has a reviewer that
    # cannot ask bench to run anything, and nothing said so.
    checks = [c["name"] for c in found["verify"]]
    blocked = [d for d in found["diagnostics"]
               if d["code"].startswith("check-") or d["code"].startswith("prepare-")]
    if blocked:
        state, detail = "failed", blocked[0]["why"]
    elif checks:
        state, detail = "passed", (
            f"may ask bench to run {', '.join(checks)} — through the "
            f"'{profiles.VERIFY_GRANT}' grant bench adds itself, and nothing "
            f"this run writes reaches an argument list")
    else:
        state, detail = "skipped", (
            f"'{intent}' names no check, so bench runs nothing on its behalf "
            f"and this run's own account of its testing is all there is")
    out.append(_finding(
        "inspect", "verification", state,
        f"whether the '{intent}' intent can ask bench to run a named check",
        detail, intent=intent,
        code=(blocked[0]["code"] if blocked else None),
        remedy=(blocked[0]["remedy"] if blocked else
                (f"Declare a check in the document's top-level \"checks\" "
                 f"list and name it in \"profiles\".\"{intent}\".\"verify\" — "
                 f"a run's own report that the tests passed is not evidence."
                 if state == "skipped" else None))))
    return out


def _pending_findings(table: dict, readings: list[dict]) -> list[dict]:
    """The guarantees nothing installed here enforces.

    Always rows, never omissions. A capability that is simply absent from
    a report reads as one that holds, which is the single most dangerous
    thing a readiness view can imply — so each is `deferred`, in that
    word, with what it would take to make it real.

    A profile that *requires* one is a different fact: that is a refusal,
    it already has a `requirement-unsupported` row of its own, and the
    launch does not start.
    """
    out = []
    for name, why in sorted(profiles.PENDING_CAPABILITIES.items()):
        requiring = sorted({r["intent"] for r in readings
                            if name in (r.get("requires") or [])})
        out.append(_finding(
            "inspect", f"pending:{name}",
            "failed" if requiring else "deferred",
            f"the '{name}' guarantee",
            (f"'{', '.join(requiring)}' requires it and nothing here enforces "
             f"it, so the launch is refused rather than run under a "
             f"restriction that exists only in the prompt. {why}"
             if requiring else why),
            code=("requirement-unsupported" if requiring else None),
            remedy=(profiles.DIAGNOSTICS["requirement-unsupported"][1]
                    if requiring else
                    f"Nothing to do — "
                    f"{(table.get(name) or {}).get('by') or 'nothing'} answers "
                    f"for it today, and a profile that requires it is refused "
                    f"rather than reported as honoured.")))
    return out


