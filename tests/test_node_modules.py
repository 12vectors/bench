"""Node's built-in test runner, wrapped so the suite stays one command (WP02).

A page helper with no DOM dependency is tested by importing it as a real
module under `node --test` — no npm, no bundler — instead of lifting its
text out of the page with a regular expression (see tests/pagesource.py).
Every `*.test.mjs` under `tests/node/` runs here, as one Python test.

What counts as a pass is strict, because a green zero-test run is the
failure this exists to prevent: Node must be there (its absence is a
skip, which `verify/backend` reads as a setup deficiency, never as a
pass), at least one test must run, and every test must pass — none
skipped, todo or cancelled.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
NODE_TESTS = REPO / "tests" / "node"
NODE = shutil.which("node")
MISSING = ("node not installed: tests/node/ runs under Node's built-in test "
           "runner, so its tests did not run (a setup deficiency, not a pass)")

COUNTS = ("tests", "suites", "pass", "fail", "cancelled", "skipped", "todo")


def node_files(root: Path = NODE_TESTS) -> list[Path]:
    return sorted(root.glob("*.test.mjs"))


def run(files: list[Path], cwd: Path = REPO) -> tuple[int, dict, str]:
    """`node --test` over `files` with the TAP reporter: its exit status,
    the summary counts it printed, and its whole output.

    Node counts a file that declares no test as one passing test named
    after the file, so the count alone cannot see an empty file. Those
    top-level subtests are counted apart, as `empty`."""
    env = {k: v for k, v in os.environ.items() if not k.startswith(("BOARD_", "AGENT_"))}
    done = subprocess.run([NODE, "--test", "--test-reporter=tap",
                           *[str(f) for f in files]],
                          cwd=str(cwd), capture_output=True, text=True,
                          timeout=300, env=env)
    out = done.stdout + done.stderr
    counts = {k: int(v) for k, v in
              re.findall(rf"^# ({'|'.join(COUNTS)}) (\d+)$", out, re.M)}
    names = {str(f) for f in files}
    counts["empty"] = sum(1 for name in re.findall(r"^# Subtest: (.+)$", out, re.M)
                          if name in names)
    return done.returncode, counts, out


def problems(code: int, counts: dict) -> list[str]:
    """Why a Node run is not a pass of the whole of it; empty when it is."""
    found = []
    if "tests" not in counts:
        return [f"node printed no TAP summary (exit {code})"]
    if counts["tests"] - counts.get("empty", 0) <= 0:
        found.append("zero tests ran — nothing was checked")
    elif counts.get("empty", 0):
        found.append(f"{counts['empty']} file(s) declared no test")
    for key in ("fail", "cancelled", "skipped", "todo"):
        if counts.get(key, 0):
            found.append(f"{counts[key]} {key}")
    if counts.get("pass", 0) != counts["tests"]:
        found.append(f"{counts.get('pass', 0)} of {counts['tests']} passed")
    if code != 0 and not found:
        found.append(f"node exited {code}")
    return found


class NodeModuleTests(unittest.TestCase):

    def setUp(self):
        if NODE is None:
            self.skipTest(MISSING)

    def test_every_node_module_test_passes(self):
        files = node_files()
        self.assertTrue(files, "no tests/node/*.test.mjs found: the wrapper is vacuous")
        code, counts, out = run(files)
        self.assertEqual(problems(code, counts), [], out[-4000:])
        self.assertGreaterEqual(counts["tests"], len(files))


class TheWrapperIsStrict(unittest.TestCase):
    """Temporary fixtures, not product modules: they prove the wrapper
    tells a pass from a failure, a skip and an empty run."""

    def setUp(self):
        if NODE is None:
            self.skipTest(MISSING)
        self.tmp = Path(tempfile.mkdtemp(prefix="bench-node-")).resolve()
        self.addCleanup(shutil.rmtree, self.tmp, True)

    def fixture(self, body: str) -> Path:
        path = self.tmp / f"f{len(list(self.tmp.iterdir()))}.test.mjs"
        path.write_text('import { test } from "node:test"\n'
                        'import assert from "node:assert/strict"\n' + body,
                        encoding="utf-8")
        return path

    def test_a_passing_fixture_passes(self):
        code, counts, _ = run([self.fixture('test("ok", () => assert.equal(1, 1))\n')],
                              cwd=self.tmp)
        self.assertEqual(problems(code, counts), [])
        self.assertEqual(counts["tests"], 1)

    def test_a_failing_fixture_is_a_failure(self):
        code, counts, _ = run([self.fixture('test("no", () => assert.equal(1, 2))\n')],
                              cwd=self.tmp)
        self.assertNotEqual(code, 0)
        self.assertIn("1 fail", problems(code, counts))

    def test_a_skip_is_not_a_pass(self):
        code, counts, _ = run([self.fixture('test("later", { skip: true }, () => {})\n')],
                              cwd=self.tmp)
        self.assertIn("1 skipped", problems(code, counts))

    def test_zero_tests_is_not_a_pass(self):
        code, counts, _ = run([self.fixture("// nothing here\n")], cwd=self.tmp)
        self.assertIn("zero tests ran — nothing was checked", problems(code, counts))

    def test_no_summary_is_not_a_pass(self):
        self.assertEqual(problems(1, {}), ["node printed no TAP summary (exit 1)"])


if __name__ == "__main__":
    unittest.main()
